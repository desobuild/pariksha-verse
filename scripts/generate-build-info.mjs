#!/usr/bin/env node
/**
 * Phase 14G — generates src/lib/observability/build-info.generated.ts.
 *
 * Two deterministic, non-sensitive identifiers are written:
 * - BUILD_VERSION:   package.json `version` (the existing source of truth;
 *                    never hand-maintained here).
 * - BUILD_COMMIT_SHA: `git rev-parse HEAD` of the checkout the build was
 *                    produced from; "unknown" when git is unavailable.
 *
 * Runs on `postinstall` (so dev/typecheck/tests always resolve the module)
 * and before every build (package.json `build`, `vinext:build`, `cf:build`),
 * so deployed artifacts always carry the real commit. The output is
 * gitignored and prettier-formatted so it never fails `format:check`.
 */

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, "..");
const outputPath = path.join(repoRoot, "src", "lib", "observability", "build-info.generated.ts");

function readPackageVersion() {
  const pkg = JSON.parse(readFileSync(path.join(repoRoot, "package.json"), "utf-8"));
  if (typeof pkg.version !== "string" || pkg.version.length === 0) {
    throw new Error("package.json has no version field");
  }
  return pkg.version;
}

function readCommitSha() {
  try {
    return execFileSync("git", ["rev-parse", "HEAD"], {
      cwd: repoRoot,
      encoding: "utf-8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    return "unknown";
  }
}

const version = readPackageVersion();
const commitSha = readCommitSha();

const contents = `// AUTO-GENERATED by scripts/generate-build-info.mjs — do not edit or commit.
// Regenerated on postinstall and before every build (see the script header).
// Annotated as string so consumers can compare against the "unknown" fallback
// without TypeScript narrowing the literal.
export const BUILD_VERSION: string = ${JSON.stringify(version)};
export const BUILD_COMMIT_SHA: string = ${JSON.stringify(commitSha)};
`;

writeFileSync(outputPath, contents, "utf-8");
process.stdout.write(
  `build-info: version=${version} commit=${commitSha.slice(0, 12)} -> ${path.relative(repoRoot, outputPath)}\n`
);
